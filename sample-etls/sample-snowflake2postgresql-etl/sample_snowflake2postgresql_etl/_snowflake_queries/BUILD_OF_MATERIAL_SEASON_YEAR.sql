        'consumerConstructDimensionName',
        ANY_VALUE(CONSUMER_CONSTRUCT_DIMENSION_NAME),
        'consumerConstructGlobalConsumerOffenseName',
        ANY_VALUE(CONSUMER_CONSTRUCT_GLOBAL_CONSUMER_OFFENSE_NAME),
        'productPlanningAgeGenderName',
        ANY_VALUE(PRODUCT_PLANNING_AGE_GENDER_NAME),
