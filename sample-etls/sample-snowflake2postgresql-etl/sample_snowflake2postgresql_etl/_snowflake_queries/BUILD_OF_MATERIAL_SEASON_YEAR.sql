    ANY_VALUE(AGE) as AGE_GROUP,
    ANY_VALUE(PRODUCT_LINE.CATEGORY) as CATEGORY,
    ANY_VALUE(CLASSIFICATION) as CLASSIFICATION,
    ANY_VALUE(BILL_OF_MATERIAL.COLORWAY) as COLORWAY,
    ANY_VALUE(DEV_TEAM) as DEVELOPMENT_TEAM,
    ANY_VALUE(BILL_OF_MATERIAL.DIVISION) as DIVISION,
    ANY_VALUE(BILL_OF_MATERIAL.FCTY) as FACTORY,
    ANY_VALUE(FIT) as FIT,
    ANY_VALUE(GENDER) as GENDER,
    ANY_VALUE(MARKETING_TYPE) as MARKETING_TYPE,
    SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2) as SEASON,
    TO_NUMBER(SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 3, 2)) + 2000 as YEAR,
    ANY_VALUE(SILHOUETTE) as SILHOUETTE,
    ANY_VALUE(STYLE_NAME) as STYLE_NAME,
    ANY_VALUE(
        IFF(
            BILL_OF_MATERIAL.STYLE IS NULL,
            NULL,
            BILL_OF_MATERIAL.STYLE
        )
    ) as STYLE_NUMBER,
    OBJECT_CONSTRUCT(
        'milestone',
        ANY_VALUE(COST_BREAKDOWN.MILESTONE),
        'technicalDifficulty',
        ANY_VALUE(COST_BREAKDOWN.TECH_DFCLTY),
        'importExportKg',
        ANY_VALUE(WEIGHTS.NET_NET),
        'demandPlanVolume',
        ROUND(
            COALESCE(SUM(DP_VOLUME / ARRAY_SIZE(BOM_IDS)), 0)
        ),
        'factory',
        ANY_VALUE(BILL_OF_MATERIAL.FCTY),
        'factoryCountry',
        ANY_VALUE(FCTY.FCTY_CTRY),
        'age',
        ANY_VALUE(AGE),
        'gender',
        ANY_VALUE(GENDER),
        'silhouette',
        ANY_VALUE(SILHOUETTE),
        'styleName',
        ANY_VALUE(STYLE_NAME),
        'classification',
