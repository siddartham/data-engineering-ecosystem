                    1,
                    0
                )
            ) || '/' || CASE
                WHEN SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2) = 'FA' THEN 1
                WHEN SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2) = 'HO' THEN 2
                WHEN SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2) = 'SP' THEN 3
                WHEN SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2) = 'SU' THEN 4
            END || '/' || BILL_OF_MATERIAL.FCTY
        ),
        'bomSource',
        ANY_VALUE(BILL_OF_MATERIAL_CYCLE_YEAR_LINE_ITEM.BILL_OF_MATERIAL_SOURCE),
        'lineItems',
        ANY_VALUE(BILL_OF_MATERIAL_CYCLE_YEAR_LINE_ITEM.LINE_ITEMS)
    ) AS DATA
FROM BILL_OF_MATERIAL
    LEFT JOIN (
        SELECT *,
            TO_VARCHAR(FLATTENED_BOM_IDS.VALUE) AS PRODUCT_DEVELOPMENT_BOM_UUID
        FROM DP_VOLUME,
            TABLE(FLATTEN(DP_VOLUME.BOM_IDS)) FLATTENED_BOM_IDS
    ) VOLUME ON BILL_OF_MATERIAL.PRODUCT_DEVELOPMENT_BOM_UUID = VOLUME.PRODUCT_DEVELOPMENT_BOM_UUID
    AND BILL_OF_MATERIAL.CYCLE_YEAR = VOLUME.CYCLE_YEAR
    LEFT JOIN WEIGHTS ON WEIGHTS.STYLE = BILL_OF_MATERIAL.STYLE
    LEFT JOIN PRODUCT_LINE ON PRODUCT_LINE.STYLE = BILL_OF_MATERIAL.STYLE
    AND PRODUCT_LINE.CYCLE_YEAR = BILL_OF_MATERIAL.CYCLE_YEAR
    AND PRODUCT_LINE.COLORWAY = BILL_OF_MATERIAL.COLORWAY
    LEFT JOIN COST_BREAKDOWN ON COST_BREAKDOWN.RANK = 1
    AND COST_BREAKDOWN.FCTY = BILL_OF_MATERIAL.FCTY
    AND COST_BREAKDOWN.COLORWAY_IDENTIFIER = BILL_OF_MATERIAL.COLORWAY_IDENTIFIER
    AND COST_BREAKDOWN.BOM_HDR_ID = BILL_OF_MATERIAL.BOM_IDENTIFIER
    LEFT JOIN PES_ARIA_PRODUCT_PROD.PROCESSED.PCX_FCTY_V FCTY ON FCTY.FCTY_LGCY_CD = BILL_OF_MATERIAL.FCTY
    LEFT JOIN BILL_OF_MATERIAL_CYCLE_YEAR_LINE_ITEM ON BILL_OF_MATERIAL_CYCLE_YEAR_LINE_ITEM.PRODUCT_DEVELOPMENT_BOM_UUID = BILL_OF_MATERIAL.PRODUCT_DEVELOPMENT_BOM_UUID
    AND BILL_OF_MATERIAL_CYCLE_YEAR_LINE_ITEM.CYCLE_YEAR = BILL_OF_MATERIAL.CYCLE_YEAR
GROUP BY BILL_OF_MATERIAL.PRODUCT_DEVELOPMENT_BOM_UUID,
    BILL_OF_MATERIAL.CYCLE_YEAR
