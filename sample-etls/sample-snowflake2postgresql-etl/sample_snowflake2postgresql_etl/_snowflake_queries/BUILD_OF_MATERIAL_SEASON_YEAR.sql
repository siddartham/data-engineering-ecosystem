        'productPlanningSubSilhouetteName',
        ANY_VALUE(PRODUCT_PLANNING_SUB_SILHOUETTE_NAME),
        'productOfferingStatusIndicator',
        ANY_VALUE(PRODUCT_OFFERING_STATUS_INDICATOR),
        'division',
        ANY_VALUE(BILL_OF_MATERIAL.DIVISION),
        'season',
        SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2),
        'seasonYear',
        TO_NUMBER(SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 3, 2)) + 2000,
        'quarter',
        CASE
            WHEN SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2) = 'FA' THEN 1
            WHEN SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2) = 'HO' THEN 2
            WHEN SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2) = 'SP' THEN 3
            WHEN SUBSTR(BILL_OF_MATERIAL.CYCLE_YEAR, 1, 2) = 'SU' THEN 4
        END,
