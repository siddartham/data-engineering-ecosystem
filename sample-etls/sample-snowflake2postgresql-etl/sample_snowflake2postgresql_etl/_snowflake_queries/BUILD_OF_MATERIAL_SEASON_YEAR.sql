WITH SEASON_YEAR AS (
    SELECT SEASON_YEAR_CD AS SEASON_YEAR_CODE,
        SEASON_NBR AS SEASON_NUMBER,
        YEAR_NBR AS YEAR_NUMBER,
        MIN(CALENDAR_DT) AS SEASON_YEAR_START
    FROM CALENDAR_PROD.BCL.ENTERPRISECALENDAR_V
    GROUP BY SEASON_YEAR_CD,
        SEASON_NBR,
        YEAR_NBR
),
IS_BILL_OF_MATERIAL_COMPLETE AS (
    SELECT PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.PRODUCT_DEVELOPMENT_BOM_UUID AS BILL_OF_MATERIAL_UUID,
        TO_VARCHAR(FLATTENED_CYCLE_YEAR.VALUE) AS CYCLE_YEAR,
        SUBSTR(TO_VARCHAR(FLATTENED_CYCLE_YEAR.VALUE), 1, 2) || '20' || SUBSTR(TO_VARCHAR(FLATTENED_CYCLE_YEAR.VALUE), 3, 2) AS SEASON_YEAR_CODE,
        PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.STYLE_NUMBER,
        PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.COLORWAY_CODE,
        PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.LEGACY_FACTORY_CODE,
        (
            CASE
                WHEN SUM(
                    CASE
                        WHEN PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.DIVISION_DESCRIPTION = 'APPAREL DIVISION' THEN CASE
                            WHEN PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.COLOR = '{}'
                            AND PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.COLOR_PLACEHOLDER_DESCRIPTION IS NULL
                            AND PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.COMPONENT_LINE_ITEM_LIST = '[]' THEN 0
                            ELSE 1
                        END
                        ELSE 1
                    END
                ) = 0 THEN FALSE
                ELSE TRUE
            END
        ) AS IS_COMPLETE
    FROM EDA_PRODUCT_PROD.BCL_GOODS_DEVELOPMENT.PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V,
        TABLE(
            FLATTEN(
                PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.CYCLE_YEAR
            )
        ) AS FLATTENED_CYCLE_YEAR
    WHERE (
            SUBSTR(TO_VARCHAR(FLATTENED_CYCLE_YEAR.VALUE), 3, 2) > 18
            OR TO_VARCHAR(FLATTENED_CYCLE_YEAR.VALUE) IN ('FA18', 'HO18')
        )
        AND BILL_OF_MATERIAL_STATUS_INDICATOR = TRUE
    GROUP BY PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.PRODUCT_DEVELOPMENT_BOM_UUID,
        FLATTENED_CYCLE_YEAR.VALUE,
        PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.COLORWAY_CODE,
        PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.LEGACY_FACTORY_CODE,
        PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.STYLE_NUMBER
),
IS_BILL_OF_MATERIAL_COMPLETE_SEASON_YEAR AS (
    SELECT IS_BILL_OF_MATERIAL_COMPLETE.BILL_OF_MATERIAL_UUID,
        IS_BILL_OF_MATERIAL_COMPLETE.CYCLE_YEAR,
        IS_BILL_OF_MATERIAL_COMPLETE.SEASON_YEAR_CODE,
        IS_BILL_OF_MATERIAL_COMPLETE.STYLE_NUMBER,
        IS_BILL_OF_MATERIAL_COMPLETE.COLORWAY_CODE,
        IS_BILL_OF_MATERIAL_COMPLETE.LEGACY_FACTORY_CODE,
        IS_BILL_OF_MATERIAL_COMPLETE.IS_COMPLETE,
        SEASON_YEAR.SEASON_YEAR_START
    FROM IS_BILL_OF_MATERIAL_COMPLETE
        JOIN SEASON_YEAR ON IS_BILL_OF_MATERIAL_COMPLETE.SEASON_YEAR_CODE = SEASON_YEAR.SEASON_YEAR_CODE
),
CANDIDATE_SUBSTITUTE_BILL_OF_MATERIAL AS (
    SELECT INCOMPLETE_BILL_OF_MATERIAL.BILL_OF_MATERIAL_UUID AS INCOMPLETE_BILL_OF_MATERIAL_UUID,
        INCOMPLETE_BILL_OF_MATERIAL.SEASON_YEAR_CODE AS INCOMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_CODE,
        INCOMPLETE_BILL_OF_MATERIAL.CYCLE_YEAR AS INCOMPLETE_BILL_OF_MATERIAL_CYCLE_YEAR,
        COMPLETE_BILL_OF_MATERIAL.BILL_OF_MATERIAL_UUID AS COMPLETE_BILL_OF_MATERIAL_UUID,
        COMPLETE_BILL_OF_MATERIAL.SEASON_YEAR_CODE AS COMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_CODE,
        COMPLETE_BILL_OF_MATERIAL.CYCLE_YEAR AS COMPLETE_BILL_OF_MATERIAL_CYCLE_YEAR,
        COMPLETE_BILL_OF_MATERIAL.SEASON_YEAR_START AS COMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_START
    FROM IS_BILL_OF_MATERIAL_COMPLETE_SEASON_YEAR AS INCOMPLETE_BILL_OF_MATERIAL
        LEFT OUTER JOIN IS_BILL_OF_MATERIAL_COMPLETE_SEASON_YEAR AS COMPLETE_BILL_OF_MATERIAL ON INCOMPLETE_BILL_OF_MATERIAL.STYLE_NUMBER = COMPLETE_BILL_OF_MATERIAL.STYLE_NUMBER
        AND INCOMPLETE_BILL_OF_MATERIAL.COLORWAY_CODE = COMPLETE_BILL_OF_MATERIAL.COLORWAY_CODE
        AND INCOMPLETE_BILL_OF_MATERIAL.LEGACY_FACTORY_CODE = COMPLETE_BILL_OF_MATERIAL.LEGACY_FACTORY_CODE
        AND INCOMPLETE_BILL_OF_MATERIAL.SEASON_YEAR_START > COMPLETE_BILL_OF_MATERIAL.SEASON_YEAR_START
        AND COMPLETE_BILL_OF_MATERIAL.IS_COMPLETE = TRUE
    WHERE INCOMPLETE_BILL_OF_MATERIAL.IS_COMPLETE = FALSE
),
SUBSTITUTE_BILL_OF_MATERIAL AS (
    SELECT INCOMPLETE_BILL_OF_MATERIAL_UUID,
        INCOMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_CODE,
        INCOMPLETE_BILL_OF_MATERIAL_CYCLE_YEAR,
        COMPLETE_BILL_OF_MATERIAL_UUID AS LATEST_COMPLETE_BILL_OF_MATERIAL_UUID,
        COMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_CODE AS LATEST_COMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_CODE,
        COMPLETE_BILL_OF_MATERIAL_CYCLE_YEAR AS LATEST_COMPLETE_BILL_OF_MATERIAL_CYCLE_YEAR
    FROM CANDIDATE_SUBSTITUTE_BILL_OF_MATERIAL QUALIFY COMPLETE_BILL_OF_MATERIAL_UUID IS NULL
        OR ROW_NUMBER() OVER (
            PARTITION BY INCOMPLETE_BILL_OF_MATERIAL_UUID,
            INCOMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_CODE
            ORDER BY COMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_START DESC
        ) = 1
),
BILL_OF_MATERIAL_HEADER AS (
    SELECT PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.PRODUCT_DEVELOPMENT_BOM_UUID,
        ANY_VALUE(
            PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.DIVISION_DESCRIPTION
        ) AS DIVISION,
        ANY_VALUE(
            PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.BOM_IDENTIFIER
        ) AS BOM_IDENTIFIER,
        ANY_VALUE(
            PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.DEVELOPMENT_COLORWAY_IDENTIFIER
        ) AS DEVELOPMENT_COLORWAY_IDENTIFIER,
        ANY_VALUE(
            PRODUCT_DEVELOPMENT_BOM_V.PRODUCT_UUID
        ) AS PRODUCT_UUID,
        ANY_VALUE(
            PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.COLORWAY_CODE
        ) AS COLORWAY_CODE,
        ANY_VALUE(
            PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.STYLE_NUMBER
        ) AS STYLE,
        ANY_VALUE(
            PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.LEGACY_FACTORY_CODE
        ) AS FCTY,
        ANY_VALUE(
            PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.CYCLE_YEAR
        ) AS CYCLE_YEAR
    FROM EDA_PRODUCT_PROD.BCL_GOODS_DEVELOPMENT.PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V
        LEFT JOIN EDA_PRODUCT_PROD.BCL_GOODS_DEVELOPMENT.PRODUCT_DEVELOPMENT_BOM_V ON PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.PRODUCT_DEVELOPMENT_BOM_UUID = PRODUCT_DEVELOPMENT_BOM_V.PRODUCT_DEVELOPMENT_BOM_UUID
        AND PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.CYCLE_YEAR = PRODUCT_DEVELOPMENT_BOM_V.CYCLE_YEAR
    WHERE PRODUCT_DEVELOPMENT_BOM_V.BILL_OF_MATERIAL_STATUS_INDICATOR = TRUE
        AND (
            (PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.DIVISION_DESCRIPTION = 'FOOTWEAR DIVISION' AND PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.IS_BOM_CONVERTED_INDICATOR = FALSE)
            OR (PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.DIVISION_DESCRIPTION = 'EQUIPMENT DIVISION' AND PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.IS_BOM_CONVERTED_INDICATOR = FALSE)
            OR (PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.DIVISION_DESCRIPTION = 'APPAREL DIVISION' AND PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.IS_BOM_CONVERTED_INDICATOR IS NULL)
            )
    GROUP BY PRODUCT_DEVELOPMENT_BOM_LINE_ITEMS_FLAT_V.PRODUCT_DEVELOPMENT_BOM_UUID
),
FLATTENED_BILL_OF_MATERIAL_HEADER AS (
    SELECT PRODUCT_DEVELOPMENT_BOM_UUID,
        DEVELOPMENT_COLORWAY_IDENTIFIER,
        COLORWAY_CODE AS BILL_OF_MATERIAL_COLORWAY_CODE,
        BOM_IDENTIFIER,
        PRODUCT_UUID,
        DIVISION,
        STYLE,
        FCTY,
        TO_VARCHAR(FLATTENED_CYCLE_YEAR.VALUE) AS CYCLE_YEAR
    FROM BILL_OF_MATERIAL_HEADER,
        TABLE(FLATTEN(BILL_OF_MATERIAL_HEADER.CYCLE_YEAR)) AS FLATTENED_CYCLE_YEAR
),
UNIFIED_BILL_OF_MATERIAL AS (
    SELECT FLATTENED_BILL_OF_MATERIAL_HEADER.PRODUCT_DEVELOPMENT_BOM_UUID,
        FLATTENED_BILL_OF_MATERIAL_HEADER.BOM_IDENTIFIER,
        COALESCE(
            SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.DEVELOPMENT_COLORWAY_IDENTIFIER,
            FLATTENED_BILL_OF_MATERIAL_HEADER.DEVELOPMENT_COLORWAY_IDENTIFIER
        ) AS COLORWAY_IDENTIFIER,
        COALESCE(
            SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.PRODUCT_UUID,
            FLATTENED_BILL_OF_MATERIAL_HEADER.PRODUCT_UUID
        ) AS PRODUCT_UUID,
        COALESCE(
            SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.STYLE,
            FLATTENED_BILL_OF_MATERIAL_HEADER.STYLE
        ) || '-' || COALESCE(
            SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.BILL_OF_MATERIAL_COLORWAY_CODE,
            FLATTENED_BILL_OF_MATERIAL_HEADER.BILL_OF_MATERIAL_COLORWAY_CODE,
            PRODUCT_COLORWAY_CODE
        ) AS PRODUCT_CODE,
        COALESCE(
            SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.BILL_OF_MATERIAL_COLORWAY_CODE,
            FLATTENED_BILL_OF_MATERIAL_HEADER.BILL_OF_MATERIAL_COLORWAY_CODE,
            PRODUCT_COLORWAY_CODE
        ) AS COLORWAY,
        COALESCE(
            SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.STYLE,
            FLATTENED_BILL_OF_MATERIAL_HEADER.STYLE
        ) AS STYLE,
        COALESCE(
            SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.DIVISION,
            FLATTENED_BILL_OF_MATERIAL_HEADER.DIVISION
        ) AS DIVISION,
        COALESCE(
            SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.FCTY,
            FLATTENED_BILL_OF_MATERIAL_HEADER.FCTY
        ) AS FCTY,
        FLATTENED_BILL_OF_MATERIAL_HEADER.CYCLE_YEAR,
        'UNIFIED BOM' AS BILL_OF_MATERIAL_SOURCE,
        SUBSTITUTE_BILL_OF_MATERIAL.LATEST_COMPLETE_BILL_OF_MATERIAL_UUID,
        SUBSTITUTE_BILL_OF_MATERIAL.LATEST_COMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_CODE,
        SUBSTITUTE_BILL_OF_MATERIAL.LATEST_COMPLETE_BILL_OF_MATERIAL_CYCLE_YEAR
    FROM FLATTENED_BILL_OF_MATERIAL_HEADER
        LEFT JOIN PES_ARIA_PRODUCT_PROD.PROCESSED.PCX_DEV_CLRWY_V COLOR ON COLOR.DEV_CLRWY_ID = FLATTENED_BILL_OF_MATERIAL_HEADER.DEVELOPMENT_COLORWAY_IDENTIFIER
        LEFT JOIN EDA_PRODUCT_PROD.BCL_PRODUCT_LIBRARY.PRODUCT_V PRODUCT ON COLOR.PROD_ID = PRODUCT.PRODUCT_IDENTIFIER
        LEFT OUTER JOIN SUBSTITUTE_BILL_OF_MATERIAL ON FLATTENED_BILL_OF_MATERIAL_HEADER.CYCLE_YEAR = SUBSTITUTE_BILL_OF_MATERIAL.INCOMPLETE_BILL_OF_MATERIAL_CYCLE_YEAR
        AND FLATTENED_BILL_OF_MATERIAL_HEADER.PRODUCT_DEVELOPMENT_BOM_UUID = SUBSTITUTE_BILL_OF_MATERIAL.INCOMPLETE_BILL_OF_MATERIAL_UUID
        LEFT OUTER JOIN FLATTENED_BILL_OF_MATERIAL_HEADER AS SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER ON SUBSTITUTE_BILL_OF_MATERIAL.LATEST_COMPLETE_BILL_OF_MATERIAL_CYCLE_YEAR = SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.CYCLE_YEAR
        AND SUBSTITUTE_BILL_OF_MATERIAL.LATEST_COMPLETE_BILL_OF_MATERIAL_UUID = SUBSTITUTE_FLATTENED_BILL_OF_MATERIAL_HEADER.PRODUCT_DEVELOPMENT_BOM_UUID
    WHERE (
            RIGHT(FLATTENED_BILL_OF_MATERIAL_HEADER.CYCLE_YEAR, 2) > '18'
            OR FLATTENED_BILL_OF_MATERIAL_HEADER.CYCLE_YEAR IN ('FA18', 'HO18')
        )
        AND (
            -- Don't include incomplete BOMs for which we have no substitute
            SUBSTITUTE_BILL_OF_MATERIAL.INCOMPLETE_BILL_OF_MATERIAL_UUID IS NULL
            OR SUBSTITUTE_BILL_OF_MATERIAL.LATEST_COMPLETE_BILL_OF_MATERIAL_UUID IS NOT NULL
        )
),
SPENDCUBE_BOMS AS (
    SELECT RANK() OVER (
            PARTITION BY PROD_CD,
            SEASON_CODE,
            SEASON_YEAR,
            FCTY_CD
            ORDER BY CBD_ID DESC
        ) AS CBD_RANK,
        PCX_MATL_ID,
        PROD_CD,
        MATERIAL_NUM,
        SPLR_MATL_NUM,
        SEASON_CODE,
        SEASON_YEAR,
        SUPPLIER_NUM,
        USAGE_UOM,
        PCC_NET_KG,
        PCC_GROSS_KG,
        CBD_SCTN,
        CMPNT_NM,
        FCTY_CD,
        DEFECTIVE_LOSS_PERC,
        GROSS,
        EFFICIENCY_PERC,
        GROSS * (EFFICIENCY_PERC) AS NET,
        GROSS * (1 - EFFICIENCY_PERC) AS WASTE,
        ROW_NUMBER() OVER (
            PARTITION BY PROD_CD,
            SEASON_CODE,
            SEASON_YEAR,
            FCTY_CD
            ORDER BY SPLR_MATL_NUM,
                CMPNT_NM
        ) AS LINE_ITEM_NUMBER
    FROM "PES_ARIA_PRODUCT_PROD"."PROCESSED"."SPENDCUBE_V"
    WHERE CBD_SCTN IN (
            'UPPER',
            'MIDSOLE',
            'OUTSOLE',
            'AIR'
        )
        AND CBD_CLAS = 'MTL'
        AND MATL_TYPE <> 'LABOR, OVERHEAD, PROCESSING'
        AND (
            SEASON_YEAR > '2018'
            OR (
                SEASON_CODE IN ('FA', 'HO')
                AND SEASON_YEAR = '2018'
            )
        )
),
SPENDCUBE_BILL_OF_MATERIAL_HEADER AS (
    SELECT PROD_CD || '_' || SEASON_CODE || SUBSTR(SEASON_YEAR, 3, 2) || '_' || FCTY_CD AS PRODUCT_DEVELOPMENT_BOM_UUID,
        NULL AS BOM_IDENTIFIER,
        NULL AS COLORWAY_IDENTIFIER,
        ANY_VALUE(GLOBAL_PRODUCT_LINE_V1.PRODUCT_UUID) AS PRODUCT_UUID,
        PROD_CD AS PRODUCT_CODE,
        SUBSTR(PROD_CD, 8, 3) AS COLORWAY,
        SUBSTR(PROD_CD, 1, 6) AS STYLE,
        'FOOTWEAR DIVISION' AS DIVISION,
        FCTY_CD AS FCTY,
        SEASON_CODE || SUBSTR(SEASON_YEAR, 3, 2) AS CYCLE_YEAR,
        'SPENDCUBE' AS BILL_OF_MATERIAL_SOURCE,
        NULL AS LATEST_COMPLETE_BILL_OF_MATERIAL_UUID,
        NULL AS LATEST_COMPLETE_BILL_OF_MATERIAL_SEASON_YEAR_CODE,
        NULL AS LATEST_COMPLETE_BILL_OF_MATERIAL_CYCLE_YEAR
    FROM SPENDCUBE_BOMS
        LEFT JOIN EDA_PRODUCT_PROD.BCL_PRODUCT_LINE.GLOBAL_PRODUCT_LINE_V1 ON SPENDCUBE_BOMS.PROD_CD = GLOBAL_PRODUCT_LINE_V1.PRODUCT_CODE
    WHERE CBD_RANK = 1
    GROUP BY PROD_CD,
        SEASON_CODE,
        SEASON_YEAR,
        FCTY_CD
),
BILL_OF_MATERIAL AS (
    SELECT *
    FROM UNIFIED_BILL_OF_MATERIAL
    UNION
    SELECT SPENDCUBE_BILL_OF_MATERIAL_HEADER.*
    FROM SPENDCUBE_BILL_OF_MATERIAL_HEADER
        LEFT JOIN UNIFIED_BILL_OF_MATERIAL ON SPENDCUBE_BILL_OF_MATERIAL_HEADER.PRODUCT_CODE = UNIFIED_BILL_OF_MATERIAL.PRODUCT_CODE
        AND SPENDCUBE_BILL_OF_MATERIAL_HEADER.CYCLE_YEAR = UNIFIED_BILL_OF_MATERIAL.CYCLE_YEAR
        AND SPENDCUBE_BILL_OF_MATERIAL_HEADER.FCTY = UNIFIED_BILL_OF_MATERIAL.FCTY
    WHERE UNIFIED_BILL_OF_MATERIAL.PRODUCT_DEVELOPMENT_BOM_UUID IS NULL
),
DP_AGG AS (
    SELECT SUBSTR(PLANNING_PRODUCT_CD, 1, 6) AS STYLE,
        SUBSTR(PLANNING_PRODUCT_CD, 8, 3) AS COLORWAY,
        SUBSTR(BUSINESS_SEASON_CD, 5, 2) || SUBSTR(BUSINESS_SEASON_CD, 3, 2) AS CYCLE_YEAR,
        SUM(DEMAND_PLAN_QTY_3_0) AS DP_VOLUME
    FROM DA_DSM_SCANALYTICS_PROD.INTEGRATED.GLBL_DEMAND_PLAN_V
    WHERE MILESTONE_CD = 'Current Forecast'
        AND DIVISION_DESC IN ('APPAREL DIVISION', 'FOOTWEAR DIVISION')
        AND DEMAND_PLAN_QTY_3_0 > 0
        AND HARMONIZED_STYLE_NBR <> '*UNK*'
    GROUP BY SUBSTR(PLANNING_PRODUCT_CD, 1, 6),
        SUBSTR(PLANNING_PRODUCT_CD, 8, 3),
        SUBSTR(BUSINESS_SEASON_CD, 5, 2) || SUBSTR(BUSINESS_SEASON_CD, 3, 2)
),
DP_VOLUME AS (
    SELECT DP_AGG.STYLE,
        DP_AGG.COLORWAY,
        DP_AGG.CYCLE_YEAR,
        ANY_VALUE(DP_AGG.DP_VOLUME) AS DP_VOLUME,
        ARRAY_CAT(
            ARRAY_AGG(DISTINCT EXACT_BOM.PRODUCT_DEVELOPMENT_BOM_UUID),
            ARRAY_AGG(
                DISTINCT INEXACT_BOM.PRODUCT_DEVELOPMENT_BOM_UUID
            )
        ) AS BOM_IDS
    FROM DP_AGG
        LEFT JOIN BILL_OF_MATERIAL AS EXACT_BOM ON EXACT_BOM.COLORWAY = DP_AGG.COLORWAY
        AND EXACT_BOM.STYLE = DP_AGG.STYLE
        AND EXACT_BOM.CYCLE_YEAR = DP_AGG.CYCLE_YEAR
        LEFT JOIN BILL_OF_MATERIAL AS INEXACT_BOM ON INEXACT_BOM.STYLE = DP_AGG.STYLE
        AND INEXACT_BOM.CYCLE_YEAR = DP_AGG.CYCLE_YEAR
        AND EXACT_BOM.PRODUCT_DEVELOPMENT_BOM_UUID IS NULL
    GROUP BY DP_AGG.STYLE,
        DP_AGG.COLORWAY,
        DP_AGG.CYCLE_YEAR
    HAVING ARRAY_SIZE(BOM_IDS) > 0
),
PRODUCT_LINE AS (
    SELECT PRODUCT_UUID,
        MAX(PRODUCT_CODE) AS PRODUCT_CODE,
        MAX(AGE_DESCRIPTION) AS AGE,
        MAX(GENDER_DESCRIPTION) AS GENDER,
        MAX(SILHOUETTE_DESCRIPTION) AS SILHOUETTE,
        MAX(STYLE_NAME) AS STYLE_NAME,
        MAX(MERCHANDISING_CLASSIFICATION_DESCRIPTION) AS CLASSIFICATION,
        MAX(GLOBAL_CATEGORY_CORE_FOCUS_DESCRIPTION) AS CATEGORY,
        MAX(FIT_DESCRIPTION) AS FIT,
        MAX(DEVELOPMENT_TEAM_NAME) AS DEV_TEAM,
        MAX(PRIMARY_MARKETING_TYPE_DESCRIPTION) AS MARKETING_TYPE,
        MAX(SUBSTR(PRODUCT_CODE, 1, 6)) AS STYLE,
        MAX(SUBSTR(PRODUCT_CODE, 8, 3)) AS COLORWAY,
        MAX(DIVISION_DESCRIPTION) AS DIVISION,
        SUBSTR(SEASON_YEAR_DESCRIPTION, 1, 2) || SUBSTR(SEASON_YEAR_DESCRIPTION, 5, 2) AS CYCLE_YEAR,
        MAX(BUSINESS_ORGANIZATION_DESCRIPTION) AS BUSINESS_ORGANIZATION,
        MAX(MODEL_OFFERING_SPONSOR_DESCRIPTION) AS SPONSOR,
        MAX(CONSUMER_PURPOSE_DESCRIPTION) AS CONSUMER_PURPOSE,
        MAX(CONSUMER_FOCUS_DESCRIPTION) AS CONSUMER_FOCUS,
        MAX(TEAM_NAME) AS TEAM_NAME,
        MAX(SUBSTR(PRODUCT_CODE, 1, 6)) AS STYLE_CODE,
        MAX(MODEL_IDENTIFIER) AS MODEL_ID,
        MAX(MODEL_NAME) AS MODEL_NAME,
        MAX(CONSUMER_USE_DESCRIPTION) AS CONSUMER_USE,
        MAX(CONSUMER_GROUP_DESCRIPTION) AS CONSUMER_GROUP,
        MAX(SUB_CATEGORY_DESCRIPTION) AS SUB_CATEGORY,
        MAX(MATERIAL_INTENT_DESCRIPTION) AS MATERIAL_INTENT,
        MAX(CONSTRUCTION_METHOD_DESCRIPTION) AS CONSTRUCTION,
        MAX(PRODUCT_TIER_DESCRIPTION) AS PRODUCT_TIER,
        TRIM(
            SPLIT_PART(
                SPLIT_PART(MAX(MARKETING_INITIATIVES), ':', 2),
                ',',
                0
            ),
            '"'
        ) AS MARKETING_INITIATIVE,
        TRIM(
            SPLIT_PART(
                SPLIT_PART(MAX(MODEL_OFFERING_GROUPS), ':', 2),
                ',',
                0
            ),
            '"'
        ) AS MO_GROUP,
        MAX(LINE_EVOLUTION_DESCRIPTION) AS LINE_EVOLUTION,
        MAX(PRODUCT_CARRYOVER_STATUS_INDICATOR) AS CARRYOVER_STATUS,
        MAX(CATEGORY_PRODUCT_LINE_MANAGER_NAME) AS PLM_NAME,
        MAX(CATEGORY_PRODUCT_LINE_MANAGER_USER_CODE) AS PLM_CODE,
        MAX(CONSUMER_CONSTRUCT_DIMENSION_NAME) AS CONSUMER_CONSTRUCT_DIMENSION_NAME,
        MAX(CONSUMER_CONSTRUCT_GLOBAL_CONSUMER_OFFENSE_NAME) AS CONSUMER_CONSTRUCT_GLOBAL_CONSUMER_OFFENSE_NAME,
        MAX(PRODUCT_PLANNING_AGE_GENDER_NAME) AS PRODUCT_PLANNING_AGE_GENDER_NAME,
        MAX(PRODUCT_PLANNING_DIVISION_NAME) AS PRODUCT_PLANNING_DIVISION_NAME,
        MAX(PRODUCT_PLANNING_INTENDED_USE_NAME) AS PRODUCT_PLANNING_INTENDED_USE_NAME,
        MAX(PRODUCT_PLANNING_SILHOUETTE_NAME) AS PRODUCT_PLANNING_SILHOUETTE_NAME,
        MAX(PRODUCT_PLANNING_STRUCTURE_NAME) AS PRODUCT_PLANNING_STRUCTURE_NAME,
        MAX(PRODUCT_PLANNING_SUB_SILHOUETTE_NAME) AS PRODUCT_PLANNING_SUB_SILHOUETTE_NAME,
        MAX(PRODUCT_OFFERING_STATUS_INDICATOR) AS PRODUCT_OFFERING_STATUS_INDICATOR
    FROM EDA_PRODUCT_PROD.BCL_PRODUCT_LINE.GLOBAL_PRODUCT_LINE_V1 GLOBAL_PRODUCT_LINE_V1
    WHERE GLOBAL_PRODUCT_LINE_V1.PRODUCT_OFFERING_STATUS_INDICATOR = 'A'
        AND GLOBAL_PRODUCT_LINE_V1.PRODUCT_UUID IS NOT NULL
        AND SEASON_YEAR_DESCRIPTION IS NOT NULL
        AND (
            CAST(SUBSTR(SEASON_YEAR_DESCRIPTION, 3, 4) AS INTEGER) > 2018
            OR SEASON_YEAR_DESCRIPTION IN ('FA2018', 'HO2018')
        )
    GROUP BY PRODUCT_UUID,
        SUBSTR(SEASON_YEAR_DESCRIPTION, 1, 2) || SUBSTR(SEASON_YEAR_DESCRIPTION, 5, 2)
),
COST_BREAKDOWN AS (
    SELECT SESN_SSYY AS CYCLE_YEAR,
        BOM_HDR_ID,
