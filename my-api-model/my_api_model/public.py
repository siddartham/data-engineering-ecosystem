def _select_product_sustainability_api_v() -> Select:
    """
    This function generates the `SELECT` statement for the view
    `PUBLIC.PRODUCT_SUSTAINABILITY_API_V`.
    """
    mapper: Mapper = get_class_mapper(BuildOfMaterialSeasonYear)
    column: Column
    return select(
        *(
            (
                column.label(
                    _translate_product_sustainability_api_column_name(
                        column.name
                    )
                )
            )
            for column in mapper.columns.values()
        )
    )


def _translate_product_sustainability_api_column_name(
    column_name: str,
) -> str:
    translated_name: str
    if column_name.upper() == "BUILD_OF_MATERIAL_ID":
        translated_name = "BOM_ID"
    elif column_name.upper() == "SEASON_YEAR_CODE":
        translated_name = "SSYY"
    elif column_name.upper() == "DEVELOPMENT_TEAM":
        translated_name = "DEV_TEAM"
    elif column_name.upper() == "YEAR":
        translated_name = "SEASON_YEAR"
    elif column_name.upper() == "AGE_GROUP":
        translated_name = "AGE"
    else:
        translated_name = column_name.upper()
    return translated_name


