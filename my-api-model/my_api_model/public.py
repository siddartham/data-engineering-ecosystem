def _iter_build_of_material_season_year_search_column_names() -> Iterable[str]:
    column: Column
    column_name: str
    return filter(
        lambda column_name: column_name != "DATA",
        map(
            lambda column: column.name,
            get_class_mapper(BuildOfMaterialSeasonYear).columns.values(),
        ),
    )


def _select_product_sustainability_api_dimensions_mv() -> Select:
    """
    This function generates the `SELECT` statement for the materialized view
    `PUBLIC.PRODUCT_SUSTAINABILITY_API_DIMENSIONS_MV`.
    """
    build_of_material_season_year_table: Table = (
        BuildOfMaterialSeasonYear.__table__
    )
    return select(
        *(
            (
                func.json_agg(
                    build_of_material_season_year_table.columns[
                        column_name
                    ].distinct()
                ).label(
                    _translate_product_sustainability_api_column_name(
                        column_name
                    )
                )
                if (
                    _translate_product_sustainability_api_column_name(
                        column_name
                    )
                    in _PRODUCT_SUSTAINABILITY_API_ENUMERATED_VALUE_COLUMNS
                )
                else literal("FUZZY").label(
                    _translate_product_sustainability_api_column_name(
                        column_name
                    )
                )
            )
            for column_name in (
                _iter_build_of_material_season_year_search_column_names()
            )
        )
    )


